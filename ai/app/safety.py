def _normalize(text: str) -> str:
    """글자(한글·자모·영문)만 남기고 소문자로 → 띄어쓰기·기호로 피해 가는 것 막기"""
    return re.sub(r"[^0-9a-z가-힣ㄱ-ㅎㅏ-ㅣ]", "", text.lower())


def check_message(message: str) -> dict | None:
    """문제 있는 말이면 { category, reply, course(bool) }, 괜찮으면 None"""
    text = _normalize(message)
    for allowed in ALLOW:
        text = text.replace(allowed, "")
    for key, cat in CATEGORIES.items():  # 위에서부터 (힘든 마음을 가장 먼저 살핌)
        if any(_normalize(w) in text for w in cat["words"]):
            lines = cat["lines"]
            return {"category": key, "reply": lines[zlib.crc32(message.encode("utf-8")) % len(lines)], "course": bool(cat.get("course"))}
    return None


