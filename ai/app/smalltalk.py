def _pick(options: list[str], message: str) -> str:
    return options[zlib.crc32(message.encode("utf-8")) % len(options)]


def detect_talk(text: str) -> str:
    """잡담 종류 (TALKS의 키) 또는 ''"""
    for key, talk in TALKS.items():
        if any(word in text for word in talk["words"]) and (not talk.get("need") or any(n in text for n in talk["need"])):
            return key
    return ""


def talk_line(key: str, message: str) -> str:
    return _pick(TALKS[key]["lines"], message) if key in TALKS else ""


def talk_effects(key: str) -> dict:
    return TALKS.get(key, {}).get("effects", {})


def bridge_line(message: str) -> str:
    return _pick(BRIDGES, message)


def offtopic_line(message: str) -> str:
    return _pick(OFFTOPIC_LINES, message)
